"""The autonomous loop: analyze -> execute -> diagnose -> repair -> execute -> verify -> retry."""
from ai.ai_debugger import get_diagnosis
from core.agent_state import AgentState
from core.analyzer import analyze
from core.executor import run_code
from core.verifier import confidence, verify
from utils.logger import AgentLogger

MAX_ATTEMPTS_LIMIT = 3  # hard cap: the loop can never be infinite


def run_agent(code, settings, on_update=None):
    log, state = AgentLogger(), AgentState(on_update)
    max_attempts = max(1, min(MAX_ATTEMPTS_LIMIT, int(settings.get("max_attempts", 3))))
    timeout = int(settings.get("timeout", 10))

    log.add("Code received")
    state.set("Code Analysis", "Running")
    analysis = analyze(code)
    log.add(f"Static analysis completed ({len(analysis['issues'])} finding(s))")
    state.set("Code Analysis", "Completed")

    state.set("Execution", "Running")
    first = run_code(code, timeout)
    current, result, attempts = code, first, []
    ok = first["success"]
    state.set("Execution", "Completed" if ok else "Failed")
    log.add("Code executed successfully" if ok else f"Code execution failed ({first['error_type']})",
            "info" if ok else "error")

    if ok:
        state.set("Error Detection", "Skipped")
        for s in ("AI Diagnosis", "Repair Generation"):
            state.set(s, "Skipped")
    for n in range(1, max_attempts + 1):
        if ok:
            break
        state.set("Error Detection", "Completed")
        log.add(f"{result['error_type']} detected at line {result['line_number']}", "error")
        info = {"code": current, "error_type": result["error_type"], "error_message": result["error_message"],
                "traceback": result["traceback"], "line_number": str(result["line_number"]),
                "static_analysis": analysis["summary"]}
        state.set("AI Diagnosis", "Running")
        diag = get_diagnosis(info, settings, log)
        state.set("AI Diagnosis", "Completed")
        log.add(f"Diagnosis generated by {diag['source']} (attempt {n})")

        state.set("Repair Generation", "Running")
        new_code = diag["repaired_code"]
        if not new_code.strip() or new_code.strip() == current.strip():
            state.set("Repair Generation", "Failed")
            log.add("No usable repair could be generated", "error")
            attempts.append({"attempt": n, "diagnosis": diag, "code_before": current,
                             "code_after": current, "result": None, "verified": False})
            break
        state.set("Repair Generation", "Completed")
        log.add("Repair generated and applied")

        state.set("Execution", "Running")
        new_result = run_code(new_code, timeout)
        state.set("Verification", "Running")
        ok, msg = verify(new_code, new_result)
        log.add(f"Repair attempt {n} executed - {msg}", "info" if ok else "error")
        attempts.append({"attempt": n, "diagnosis": diag, "code_before": current, "code_after": new_code,
                         "result": new_result, "verified": ok})
        current, result = new_code, new_result
        state.set("Execution", "Completed" if ok else "Failed")

    if ok:
        state.set("Verification", "Completed")
        log.add("Verification successful")
    else:
        state.set("Verification", "Failed")
        log.add("Autonomous repair could not resolve the issue", "error")

    status = ("already_working" if not attempts and first["success"]
              else "success" if ok else "failed")
    last_diag = next((a["diagnosis"] for a in reversed(attempts)), None)
    return {"status": status, "original_code": code, "final_code": current,
            "original_result": first, "final_result": result, "analysis": analysis,
            "attempts": attempts, "logs": log.entries, "stages": state.stages,
            "confidence": confidence(last_diag, ok, len(attempts)) if status != "already_working" else None,
            "error_type": first["error_type"] if not first["success"] else "None"}
